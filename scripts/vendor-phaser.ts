#!/usr/bin/env tsx
import { createHash } from 'node:crypto';
/**
 * Fetch and commit the third-party library that Forge vendors into generated
 * games, so an approved artifact carries its own engine instead of loading one
 * from a CDN at run time.
 *
 * This script exists because the alternative is trusting where a byte sequence
 * came from. It pins the exact URL, the exact sha256 of the library bytes and
 * the exact sha256 of the license text, fetches once, and writes a generated
 * module that the server reads. It refuses to write anything if the fetched
 * bytes do not hash to the pin, so a compromised or truncated download cannot
 * become the product's copy of Phaser. The fetched bytes are never executed
 * here; only hashed and written.
 *
 *   pnpm run vendor:phaser              fetch the pinned version, verify, write
 *   pnpm run vendor:phaser -- --check   verify the committed copy, fetch nothing
 *
 * A game that needs a different Phaser version is not silently re-pointed at
 * this one: the artifact keeps its own reference and Forge reports a named
 * vendor gap for it (KI-53).
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const VENDOR_DIR = join(ROOT, 'apps', 'server', 'src', 'forge', 'vendor');

/** The pin. Change the version deliberately, never by accident. */
export const PHASER_PIN = {
  name: 'phaser',
  version: '3.80.1',
  url: 'https://cdn.jsdelivr.net/npm/phaser@3.80.1/dist/phaser.min.js',
  licenseUrl: 'https://raw.githubusercontent.com/phaserjs/phaser/v3.80.1/LICENSE.md',
  /** Fetched from the npm tarball for this exact version, because that is the copy the URL serves. */
  tarball: 'https://registry.npmjs.org/phaser/-/phaser-3.80.1.tgz',
  sha256: '62081f6a1b51d040473f919ffedef9009953c20833518e146da5a8d1c9405ea8',
  bytes: 1_181_917,
} as const;

const sha256 = (bytes: Uint8Array | string): string =>
  createHash('sha256').update(bytes).digest('hex');

async function fetchBytes(url: string, label: string): Promise<Buffer> {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) {
    throw new Error(`could not fetch ${label} (${String(response.status)}) from ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

/**
 * The generated module. Base64 rather than a string literal: minified library
 * code contains backticks and `${`, and an escaping bug in a 1.1 MB literal is
 * exactly the kind of defect a hash check catches late. Base64 has no such
 * characters, so the bytes round-trip by construction.
 */
function moduleSource(library: Buffer, license: string): string {
  return `// GENERATED by scripts/vendor-phaser.ts — do not edit by hand.
// Rerun \`pnpm run vendor:phaser\` to regenerate, \`-- --check\` to verify in place.
//
// Phaser ${PHASER_PIN.version} (${String(library.byteLength)} bytes, sha256
// ${PHASER_PIN.sha256}) under the MIT license; the license text is included
// below and is embedded in every artifact that receives this library, because
// the license requires the notice to travel with copies.
//
// This file is a hashed build input: the production bundle's identity hash
// covers it, and the server verifies these bytes by sha256 before inlining them.

export const PHASER_VENDOR_PIN = {
  name: ${JSON.stringify(PHASER_PIN.name)},
  version: ${JSON.stringify(PHASER_PIN.version)},
  url: ${JSON.stringify(PHASER_PIN.url)},
  sha256: ${JSON.stringify(PHASER_PIN.sha256)},
  bytes: ${String(library.byteLength)},
  licenseSha256: ${JSON.stringify(sha256(license))},
} as const;

/** The MIT license text, shipped with the library and embedded in artifacts that use it. */
export const PHASER_LICENSE = ${JSON.stringify(license)};

/** The library source, base64-encoded so the bytes survive every toolchain hop. */
export const PHASER_SOURCE_BASE64 = ${JSON.stringify(library.toString('base64'))};
`;
}

async function main(): Promise<void> {
  const checkOnly = process.argv.slice(2).includes('--check');
  const modulePath = join(VENDOR_DIR, 'phaser-3.80.1.ts');

  if (checkOnly) {
    if (!existsSync(modulePath)) {
      console.error(`FAIL: ${modulePath} is missing. Run \`pnpm run vendor:phaser\`.`);
      process.exit(1);
    }
    const source = await readFile(modulePath, 'utf8');
    const match = /export const PHASER_SOURCE_BASE64 = "([^"]*)";/.exec(source);
    if (!match) {
      console.error(`FAIL: ${modulePath} does not hold a base64 library payload.`);
      process.exit(1);
    }
    const encoded = match[1] ?? '';
    const library = Buffer.from(encoded, 'base64');
    const got = sha256(library);
    if (got !== PHASER_PIN.sha256 || library.byteLength !== PHASER_PIN.bytes) {
      console.error(
        `FAIL: the committed Phaser copy is not the pinned one.\n  expected sha256 ${PHASER_PIN.sha256} (${String(PHASER_PIN.bytes)} bytes)\n  found    sha256 ${got} (${String(library.byteLength)} bytes)`,
      );
      process.exit(1);
    }
    console.log(
      `PASS: the committed Phaser ${PHASER_PIN.version} copy hashes to the pin (${String(library.byteLength)} bytes). No network was used.`,
    );
    return;
  }

  const library = await fetchBytes(PHASER_PIN.url, 'Phaser library');
  const got = sha256(library);
  if (got !== PHASER_PIN.sha256) {
    console.error(
      `FAIL: ${PHASER_PIN.url} served bytes that hash to ${got}, not the pinned ${PHASER_PIN.sha256}. Nothing was written.`,
    );
    process.exit(1);
  }
  if (library.byteLength !== PHASER_PIN.bytes) {
    console.error(
      `FAIL: the fetched library is ${String(library.byteLength)} bytes, not the pinned ${String(PHASER_PIN.bytes)}. Nothing was written.`,
    );
    process.exit(1);
  }

  // The license text: the pinned tag's file, falling back to the npm tarball of
  // the same version if the repository moved it. Either way the hash recorded in
  // the generated module is the hash of what was actually shipped.
  let license: string;
  try {
    license = (await fetchBytes(PHASER_PIN.licenseUrl, 'Phaser license')).toString('utf8');
  } catch {
    const tarball = await fetchBytes(PHASER_PIN.tarball, 'Phaser tarball');
    license = await extractLicenseFromTarball(tarball);
  }
  if (!/MIT License/i.test(license)) {
    console.error('FAIL: the fetched license text does not read like the MIT license.');
    process.exit(1);
  }

  await mkdir(VENDOR_DIR, { recursive: true, mode: 0o700 });
  await writeFile(modulePath, moduleSource(library, license), 'utf8');
  console.log(
    `PASS: vendored Phaser ${PHASER_PIN.version} (${String(library.byteLength)} bytes, sha256 ${got}) into ${modulePath}.`,
  );
}

/** Pull `package/LICENSE.md` out of an npm tarball without depending on tar. */
async function extractLicenseFromTarball(tarball: Buffer): Promise<string> {
  const text = tarball.toString('latin1');
  const at = text.indexOf('The MIT License');
  if (at === -1) throw new Error('the tarball holds no MIT license text');
  const end = text.indexOf('\u0000', at);
  return text.slice(at, end === -1 ? at + 1_200 : end).trim();
}

await main();
