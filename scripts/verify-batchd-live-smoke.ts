/**
 * Batch D — scoped LIVE acceptance smoke for voice and video understanding.
 *
 * Batch D's product behaviour (token-gated playback, download, selection
 * fencing) is proven offline. What has never been recorded is a real answer from
 * the two capabilities the batch advertises: Muse Voice Transcribe over a real
 * recording, and Muse Spark clip observation over a real MP4. This harness turns
 * each into measured evidence, in one paid call per capability, with the call
 * budget enforced at the provider boundary:
 *
 *   FORGE_MEDIA_MAX_RETRIES=0  a submission can never become two dispatches
 *   FORGE_MEDIA_TRACE=1        one bounded, secret-free line per attempt
 *   FORGE_FALLBACK_API_KEY     scrubbed from the server environment
 *   FORGE_MUSE_BIN=/bin/false  no coding call can hide inside this run
 *   MODEL_PROVIDER=echo        the chat surface cannot spend quota either
 *
 * What is measured, not asserted vaguely:
 *  - the fixture is generated and probed locally; the server must record the same
 *    sha256 and byte_size it was given, so "the provider heard X" means X really
 *    left this machine;
 *  - the audio fixture is generated by speaking a known sentence with `say`, so
 *    the transcript has a known target. Word agreement is reported as a ratio
 *    (not an accuracy score), and the run fails if the sentence's content words
 *    are missing — an empty or unrelated transcript is a real failure;
 *  - turn and observation timestamps are checked against the duration measured
 *    from the uploaded file, independently of the server's own guard;
 *  - clip observations are reported for a human to read, with lexical agreement
 *    against what the clip actually shows (a red frame with a green square
 *    crossing it). Nothing here claims to judge model quality.
 *  - trace lines must show attempt=1 only, and every response must carry
 *    provider_attempts: 1.
 *
 * Modes:
 *   BATCHD_SMOKE_FIXTURE_ONLY=1  build and probe the fixtures, make no network
 *                                call at all, write a report, exit 0. This is the
 *                                offline check of the harness's own plumbing.
 *   BATCHD_SMOKE_SCOPE=audio     default: transcription only (cheapest measurement)
 *   BATCHD_SMOKE_SCOPE=video     clip observation only
 *   BATCHD_SMOKE_SCOPE=both      one call of each
 *   BATCHD_SMOKE_TRANSCRIBE_MODE=PUSH_TO_TALK|ENDPOINTING|DIARIZATION (default ENDPOINTING,
 *                                the mode that reports turn timestamps)
 *   BATCHD_SMOKE_PHRASE / BATCHD_SMOKE_KEYWORDS  override the spoken sentence and
 *                                the words that must come back
 *
 * Requirements for a live run: FORGE_MUSE_API_KEY (never printed), ffmpeg, ffprobe,
 * and `/usr/bin/say` (macOS) unless BATCHD_SMOKE_AUDIO_WAV points at a recorded WAV.
 * No browser is needed: this harness drives the HTTP surface directly. The Studio
 * UI wiring for transcripts stays covered by the offline gates
 * (`verify:batchd-playback-auth`, `verify:batchc-ui`, `verify:studio-workflow`).
 *
 * Usage (live):
 *   FORGE_MUSE_API_KEY=... BATCHD_SMOKE_SCOPE=both pnpm verify:batchd-live-smoke
 * Usage (offline plumbing check):
 *   BATCHD_SMOKE_FIXTURE_ONLY=1 pnpm verify:batchd-live-smoke
 */
