const ROOT = process.cwd();
const STAMP = new Date().toISOString().slice(0, 16).replace('T', '-').replace(':', '');
const EVIDENCE = join(ROOT, 'test-results', 'batchd-live', STAMP);
const KEY = process.env.FORGE_MUSE_API_KEY ?? '';

interface Report {
  status: string;
  scope: string;
  completed_checks: number;
  checks: Array<{ name: string; ok: boolean }>;
  observations: Record<string, unknown>;
  calls: Record<string, number>;
  harness_limits: string[];
  error?: string;
}

const checks: Array<{ name: string; ok: boolean }> = [];
const observations: Record<string, unknown> = {};
const calls = {
  transcribe: 0,
  clip: 0,
  vision: 0,
  imageGeneration: 0,
  coding: 0,
  /** Uploads are a provider request but not a model call; counted separately. */
  uploads: 0,
  /** Dispatches on paths this run's scope does not authorize. */
  otherPaidPaths: 0,
};

const LIMITS = [
  'A word-overlap ratio measures whether the recorded words came back; it is not a transcription accuracy score.',
  'Clip observations are reported for a human to read. Lexical agreement with the clip is a signal, not a judgement of model quality.',
  'This harness drives the HTTP surface. Studio UI wiring for transcripts is covered offline by verify:batchd-playback-auth and the fixture suites, not here.',
  '/api/meta names all five media models (image, SAM, vision, transcription, video) and max_retries; each response additionally reports the model it observed, and every dispatch leaves its own trace line.',
  'One call per capability is a sample, not a distribution. Do not read a single pass as reliability.',
];

function check(name: string): void {
  checks.push({ name, ok: true });
  console.log(`  ✓ ${name}`);
}

function fail(message: string): never {
  throw new Error(message);
}

function writeReport(status: string, error?: string): void {
  // The ledger is read from the adapter's own trace every time a report is
  // written — pass, blocked, or failed. Counters that only advanced on a success
  // path hide the cost of a run that paid for a call and then failed, which is
  // exactly what a reader of the evidence needs to see.
  try {
    const logPath = join(EVIDENCE, 'server.log');
    const ledger = accountDispatches(
      parseMediaTrace(existsSync(logPath) ? readFileSync(logPath, 'utf8') : ''),
    );
    const countOn = (path: string): number =>
      ledger.dispatches.filter((entry) => entry.path === path).length;
    calls.transcribe = countOn('/v1/asr/transcribe');
    calls.clip = countOn(CLIP_MODEL_PATH);
    calls.uploads = countOn(CLIP_UPLOAD_PATH);
    calls.otherPaidPaths = ledger.dispatches.filter(
      (entry) => ![CLIP_MODEL_PATH, CLIP_UPLOAD_PATH, '/v1/asr/transcribe'].includes(entry.path),
    ).length;
    observations.dispatch_ledger = ledger.dispatches.map((entry) => ({
      path: entry.path,
      attempt: entry.attempt,
      outcome: entry.outcome ?? null,
      status: entry.status ?? null,
    }));
    observations.unpaired_outcome_lines = ledger.unpairedOutcomes.length;
    observations.unanswered_dispatches = ledger.unanswered.length;
  } catch {
    observations.dispatch_ledger = 'the server log could not be read for the ledger';
  }
  const report: Report = {
    status,
    scope: `${process.env.BATCHD_SMOKE_FIXTURE_ONLY ? 'fixtures only, no network' : `live ${process.env.BATCHD_SMOKE_SCOPE ?? 'audio'}`}`,
    completed_checks: checks.filter((entry) => entry.ok).length,
    checks,
    observations,
    calls,
    harness_limits: LIMITS,
    ...(error === undefined ? {} : { error }),
  };
  writeFileSync(join(EVIDENCE, 'report.json'), `${JSON.stringify(report, null, 2)}\n`, 'utf8');
}

const FFPROBE = FFPROBE_BIN;
const FFMPEG = FFMPEG_BIN;

function run(command: string, args: string[], cwd: string): void {
  const result = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0) {
    fail(
      `${command} failed (exit ${String(result.status)}): ${String(result.stderr ?? '').slice(0, 300)}`,
    );
  }
}

function sha256(bytes: Buffer): string {
  return createHash('sha256').update(bytes).digest('hex');
}

interface ApiEnvelope {
  ok?: boolean;
  data?: unknown;
  error?: { code?: string; message?: string };
}

async function postJson(
  url: string,
  body: unknown,
): Promise<{ status: number; json: ApiEnvelope | null }> {
  const response = await fetch(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body),
  });
  const json = (await response.json().catch(() => null)) as ApiEnvelope | null;
  return { status: response.status, json };
}

/** Is an external tool present? A missing one is a local blocker, not a result. */
function toolAvailable(command: string): boolean {
  const probe = spawnSync(command, ['-version'], { stdio: ['ignore', 'pipe', 'pipe'] });
  return probe.error === undefined && probe.status === 0;
}

async function main(): Promise<void> {
  mkdirSync(EVIDENCE, { recursive: true });
  const scope = liveScope(process.env);
  const fixtureOnly = process.env.BATCHD_SMOKE_FIXTURE_ONLY === '1';
  console.log(
    `Batch D live smoke — scope ${scope.audio ? 'audio ' : ''}${scope.video ? 'video' : ''}${fixtureOnly ? ' (fixtures only, no network)' : ''}`,
  );

  // ---- plans first, then the local prerequisites ---------------------------
  // Planning is pure: it names the recipe without touching the filesystem. The
  // prerequisite check has to come before the recipe runs so a host without `say`
  // or ffmpeg hears "this machine cannot build the fixture" rather than watching a
  // half-built fixture fail its probe, or — worse — being handed a silent WAV that a
  // model then fails to transcribe.
  const speech = speechFixturePlan(EVIDENCE, {
    phrase: scope.phrase,
    rate: Number(process.env.BATCHD_SMOKE_SPEECH_RATE ?? 165),
  });
  const clip = clipFixturePlan(EVIDENCE);
  const audioOverride = process.env.BATCHD_SMOKE_AUDIO_WAV;
  const videoOverride = process.env.BATCHD_SMOKE_VIDEO_MP4;
  const wavPath = audioOverride ?? speech.wavPath;
  const mp4Path = videoOverride ?? clip.mp4Path;

  const prerequisites = missingLivePrerequisites({
    scope,
    audioSupplied: audioOverride !== undefined,
    videoSupplied: videoOverride !== undefined,
    videoPresent: !scope.video || existsSync(mp4Path),
    platform: process.platform,
    hasSay: existsSync('/usr/bin/say'),
    hasFfmpeg: toolAvailable(FFMPEG),
    hasFfprobe: toolAvailable(FFPROBE),
  });
  if (prerequisites.length > 0) {
    observations.blocker = prerequisites;
    writeReport('BLOCKED before any provider call: local prerequisites missing');
    for (const line of prerequisites) console.error(`FAIL: missing prerequisite: ${line}`);
    console.error(`evidence: ${EVIDENCE}`);
    process.exitCode = 2;
    return;
  }
  check(
    `this host can build the fixtures for scope ${scope.audio ? 'audio ' : ''}${scope.video ? 'video' : ''} before any credential or dispatch`,
  );

  // ---- fixtures: generated, probed, hashed (never committed) ----------------
  if (audioOverride === undefined) {
    for (const step of speech.steps) run(step.command, step.args, ROOT);
  }
  if (!existsSync(wavPath)) fail(`audio fixture missing at ${wavPath}`);
  const wav = readFileSync(wavPath);
  if (scope.video) {
    for (const step of clip.steps) run(step.command, step.args, ROOT);
  }
  if (scope.video && !existsSync(mp4Path)) fail(`video fixture missing at ${mp4Path}`);
  const mp4 = scope.video ? readFileSync(mp4Path) : Buffer.alloc(0);

  const probeOf = (path: string): ReturnType<typeof parseProbe> =>
    parseProbe(JSON.parse(spawnText(FFPROBE, ffprobeArgs(path))));
  const audioProbe = probeOf(wavPath);
  const audioIssues = probeIssues(audioProbe, {
    codec: speech.expect.codec,
    sampleRate: speech.expect.sampleRate,
    channels: speech.expect.channels,
  });
  if (audioIssues.issues.length > 0) {
    fail(`audio fixture does not match its recipe: ${audioIssues.issues.join('; ')}`);
  }
  observations.audioFixture = {
    path: wavPath,
    bytes: wav.length,
    sha256: sha256(wav),
    probe: audioProbe,
    recipe: audioOverride ?? speech.steps.map((step) => [step.command, ...step.args].join(' ')),
    phrase: scope.phrase,
  };
  check(
    `speech fixture is real 16 kHz PCM (${String(audioProbe?.durationMs)}ms, ${String(wav.length)} bytes, sha ${sha256(wav).slice(0, 12)}…)`,
  );

  if (scope.video) {
    const videoProbe = probeOf(mp4Path);
    const videoIssues = probeIssues(videoProbe, clip.expect);
    if (videoIssues.issues.length > 0) {
      fail(`video fixture does not match its recipe: ${videoIssues.issues.join('; ')}`);
    }
    // A control is only a control if the request asks about what was rendered:
    // otherwise empty observations could mean the model failed to describe the
    // scene, or that it was never asked about it.
    const promptIssues = clipPromptIssues(clip.prompt);
    if (promptIssues.length > 0) {
      fail(`the clip prompt does not match the clip recipe: ${promptIssues.join('; ')}`);
    }
    check('the clip prompt names what the clip recipe renders, so a refusal is a model result');
    observations.videoFixture = {
      path: mp4Path,
      bytes: mp4.length,
      sha256: sha256(mp4),
      prompt: clip.prompt,
      expected_tokens: clip.expectedTokens,
      probe: videoProbe,
      recipe: process.env.BATCHD_SMOKE_VIDEO_MP4
        ? 'provided by BATCHD_SMOKE_VIDEO_MP4'
        : clip.steps.map((step) => [step.command, ...step.args].join(' ')),
    };
    check(
      `clip fixture is real H.264 (${String(videoProbe?.width)}x${String(videoProbe?.height)}, ${String(videoProbe?.durationMs)}ms, ${String(mp4.length)} bytes, sha ${sha256(mp4).slice(0, 12)}…)`,
    );
  }

  if (fixtureOnly) {
    observations.network_calls_made = 0;
    writeReport('fixtures built and probed; no provider call was made');
    console.log(
      `\nBatch D live-smoke fixtures: PASS (${String(checks.length)} checks, no network)`,
    );
    console.log(`evidence: ${EVIDENCE}`);
    return;
  }

  // ---- a live run refuses to start without the credential it needs ----------
  if (KEY.length === 0) {
    observations.blocker =
      'FORGE_MUSE_API_KEY is not set, so no live transcription or clip call can be made.';
    writeReport('BLOCKED before any provider call');
    console.error(
      '\nFAIL: FORGE_MUSE_API_KEY is not set — nothing was called and nothing was spent.',
    );
    console.error(`evidence: ${EVIDENCE}`);
    process.exitCode = 2;
    return;
  }

  // ---- the server under test: production bundle, one attempt per call -------
  const dataRoot = mkdtempSync(join(tmpdir(), 'batchd-live-'));
  // The reservation belongs to this harness and must succeed before a server
  // starts: `PORT=0` would let the OS pick a different port while this process
  // probed the one it thought it had.
  const serverPort = await reserveLoopbackPort().catch((error: unknown) =>
    fail(error instanceof Error ? error.message : String(error)),
  );
  const apiBase = `http://127.0.0.1:${serverPort}`;
  const serverLog = join(EVIDENCE, 'server.log');
  const env: NodeJS.ProcessEnv = {
    ...process.env,
    NODE_ENV: 'production',
    HOST: '127.0.0.1',
    PORT: String(serverPort),
    DATABASE_PATH: join(dataRoot, 'memory.db'),
    WORKSPACE_ROOT: join(dataRoot, 'workspaces'),
    CORS_ORIGINS: apiBase,
    MODEL_PROVIDER: 'echo',
    MUSE_BIN: '/bin/false',
    FORGE_MUSE_BIN: '/bin/false',
    FORGE_MEDIA_MAX_RETRIES: '0',
    FORGE_MEDIA_TRACE: '1',
    LOG_LEVEL: 'warn',
  };
  delete env.FORGE_FALLBACK_API_KEY;
  if (!existsSync(join(ROOT, 'apps/server/dist/index.js'))) {
    fail(
      'apps/server/dist/index.js is missing — run pnpm exec tsx scripts/build-production-bundles.ts',
    );
  }
  const server = spawn(process.execPath, [join(ROOT, 'apps/server/dist/index.js')], {
    cwd: ROOT,
    env,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  writeFileSync(serverLog, '', 'utf8');
  server.stdout.on('data', (chunk: Buffer) => appendFileSync(serverLog, chunk));
  server.stderr.on('data', (chunk: Buffer) => appendFileSync(serverLog, chunk));
  const projectId = `batchd-live-${STAMP}`;
  try {
    // A bound port is not a running service. Probe until the health endpoint
    // answers, and if it never does say whether the process is still alive: an
    // unparseable config error and a slow cold start look identical otherwise.
    const ready = await waitForServerReady({
      port: serverPort,
      timeoutMs: SERVER_READY_TIMEOUT_MS,
      probe: async (port) => (await fetch(`http://127.0.0.1:${port}/api/health`)).status === 200,
    });
    if (!ready.ready) {
      const state =
        server.exitCode === null && server.signalCode === null
          ? 'the process stayed running'
          : `the process exited with code ${String(server.exitCode)} signal ${String(server.signalCode)}`;
      fail(
        `the server never became healthy on port ${String(serverPort)} after ${String(ready.attempts)} probes over ${String(SERVER_READY_TIMEOUT_MS)}ms (${state})${ready.lastError === undefined ? '' : `: ${ready.lastError}`}`,
      );
    }
    observations.server_ready_after_probes = ready.attempts;
    check(`the server answered readiness probes on the reserved port ${String(serverPort)}`);

    const metaResponse = (await (await fetch(`${apiBase}/api/meta`)).json().catch(() => null)) as {
      data?: { media?: unknown };
    } | null;
    const media = metaResponse?.data?.media;
    const metaIssues = mediaMetaIssues(media);
    if (metaIssues.length > 0) fail(metaIssues.join('; '));
    observations.server_media_config = media ?? null;
    check(
      `server is live with zero transport retries and names every model a call could pay (${MEDIA_MODEL_FIELDS.join(', ')})`,
    );

    const projectId_ = projectId;
    const upload = async (mime: 'audio/wav' | 'video/mp4', bytes: Buffer, name: string) => {
      const response = await postJson(`${apiBase}/api/forge/projects/${projectId_}/media/sources`, {
        mime,
        data_base64: bytes.toString('base64'),
        origin: 'upload',
        original_name: name,
      });
      if (response.status !== 201 || response.json?.data === undefined) {
        fail(
          `upload of ${name} failed: HTTP ${String(response.status)} ${JSON.stringify(response.json?.error ?? null).slice(0, 300)}`,
        );
      }
      const record = response.json.data as { source_id: string; sha256: string; byte_size: number };
      if (record.sha256 !== sha256(bytes) || record.byte_size !== bytes.length) {
        fail(
          `${name}: server recorded sha ${String(record.sha256).slice(0, 16)}… / ${String(record.byte_size)} bytes, expected ${sha256(bytes).slice(0, 16)}… / ${String(bytes.length)}`,
        );
      }
      return record as { source_id: string; sha256: string; byte_size: number };
    };

    // Per-operation dispatch accounting. The closing sweep over known provider
    // paths cannot attribute a dispatch to the call that caused it: `/v1/responses`
    // is the path clip observation, vision and coding all share, so a coding call
    // hiding inside a clip step would look like the clip's own dispatch. Slicing the
    // trace by what was already written before the operation ran pins the budget to
    // the operation that spent it.
    const tracedSoFar = (): number => parseMediaTrace(readFileSync(serverLog, 'utf8')).length;
    const accountOperation = (
      label: string,
      from: number,
      allowedPaths: readonly string[],
      maxDispatches: number,
    ): DispatchAccount => {
      const fresh = parseMediaTrace(readFileSync(serverLog, 'utf8')).slice(from);
      // Two log lines per call (start + outcome). Counting lines double-charged
      // every call and turned each outcome line into a phantom path, so a single
      // permitted call read as a dispatch on "(unattributed)".
      const accounted = accountDispatches(fresh);
      const paths = accounted.paths;
      observations[`trace_${label.replace(/\W+/g, '_')}`] = {
        trace_lines: fresh.length,
        dispatches: accounted.dispatches.length,
        paths,
        attempts: accounted.dispatches.map((entry) => ({
          attempt: entry.attempt,
          path: entry.path,
          outcome: entry.outcome ?? null,
          status: entry.status ?? null,
        })),
        maxAttempt: accounted.maxAttempt,
        unpaired_outcomes: accounted.unpairedOutcomes.length,
        unanswered: accounted.unanswered.length,
      };
      if (accounted.dispatches.length === 0) {
        fail(
          `${label} produced no traced provider dispatch, so its call budget cannot be accounted for`,
        );
      }
      if (accounted.unpairedOutcomes.length > 0) {
        fail(
          `${label} has ${String(accounted.unpairedOutcomes.length)} provider outcome(s) no start line accounts for`,
        );
      }
      if (accounted.unanswered.length > 0) {
        fail(
          `${label} has ${String(accounted.unanswered.length)} dispatch(es) whose outcome never arrived`,
        );
      }
      const unexpected = paths.filter((path) => !allowedPaths.includes(path));
      if (unexpected.length > 0) {
        fail(`${label} dispatched on paths it must not touch: ${unexpected.join(', ')}`);
      }
      if (accounted.maxAttempt > 1) {
        fail(`${label} was retried: a dispatch reached attempt ${String(accounted.maxAttempt)}`);
      }
      if (accounted.dispatches.length > maxDispatches) {
        fail(
          `${label} spent ${String(accounted.dispatches.length)} dispatches where this run allows at most ${String(maxDispatches)}`,
        );
      }
      check(
        `${label} accounted for ${String(accounted.dispatches.length)} dispatch(es) on ${paths.join(', ')}, none beyond attempt 1`,
      );
      return accounted;
    };

    if (scope.audio) {
      const traceBefore = tracedSoFar();
      const record = await upload('audio/wav', wav, 'speech.wav');
      const response = await postJson(
        `${apiBase}/api/forge/projects/${projectId_}/media/sources/${record.source_id}/transcribe`,
        { mode: scope.mode, language_bias: ['en'], keywords: scope.keywords },
      );
      if (response.status !== 200 || response.json?.data === undefined) {
        observations.transcribeFailure = {
          status: response.status,
          code: response.json?.error?.code ?? null,
          message: String(response.json?.error?.message ?? '').slice(0, 300),
        };
        fail(
          `transcription failed: HTTP ${String(response.status)} ${JSON.stringify(observations.transcribeFailure)}`,
        );
      }
      const transcript = MediaTranscriptSchema.parse(response.json.data);
      // Counted from what the response itself reports, not from the click.
      calls.transcribe = transcript.provider_attempts;
      const match = transcriptMatch(scope.phrase, transcript.transcript, scope.keywords);
      const turnIssues = timestampIssues(
        transcript.turns.map((turn) => ({
          start_ms: turn.start_ms,
          end_ms: turn.end_ms,
          text: turn.text,
        })),
        transcript.duration_ms,
      );
      observations.transcription = {
        source_id: transcript.source_id,
        mode: scope.mode,
        model: transcript.model,
        observed_model: transcript.observed_model,
        provider_attempts: transcript.provider_attempts,
        measured_duration_ms: transcript.duration_ms,
        provider_reported_duration_ms: transcript.audio_duration_ms,
        turns: transcript.turns.length,
        turn_timestamp_issues: turnIssues,
        word_agreement: {
          spoken_content_words: match.spokenWords,
          matched: match.matchedWords,
          ratio: Number(match.ratio.toFixed(3)),
          keywords_expected: match.keywordsExpected,
          keywords_found: match.keywordsFound,
          keywords_missing: match.keywordsMissing,
        },
        excerpt: boundedExcerpt(transcript.transcript),
      };
      if (transcript.provider_attempts !== 1) {
        fail(
          `transcription took ${String(transcript.provider_attempts)} dispatches, expected exactly 1`,
        );
      }
      if (transcript.duration_ms !== audioProbe?.durationMs) {
        fail(
          `server measured ${String(transcript.duration_ms)}ms from the uploaded file, local probe says ${String(audioProbe?.durationMs)}ms`,
        );
      }
      if (turnIssues.length > 0)
        fail(`turn timestamps fall outside the clip: ${turnIssues.join('; ')}`);
      if (match.keywordsMissing.length > 0) {
        fail(
          `the transcript is missing the words we know were spoken: ${match.keywordsMissing.join(', ')} (agreement ${String(match.matchedWords)}/${String(match.spokenWords)})`,
        );
      }
      check(
        `live transcription heard ${String(match.matchedWords)}/${String(match.spokenWords)} content words (model ${transcript.observed_model ?? transcript.model}, one dispatch)`,
      );
      accountOperation('transcription', traceBefore, ['/v1/asr/transcribe'], 1);
    }

    if (scope.video) {
      const traceBefore = tracedSoFar();
      const record = await upload('video/mp4', mp4, 'clip.mp4');
      const response = await postJson(
        `${apiBase}/api/forge/projects/${projectId_}/media/sources/${record.source_id}/clip`,
        { prompt: clip.prompt },
      );
      if (response.status !== 200 || response.json?.data === undefined) {
        observations.clipFailure = {
          status: response.status,
          code: response.json?.error?.code ?? null,
          message: String(response.json?.error?.message ?? '').slice(0, 300),
        };
        fail(
          `clip observation failed: HTTP ${String(response.status)} ${JSON.stringify(observations.clipFailure)}`,
        );
      }
      const clipResponse = MediaClipResponseSchema.parse(response.json.data);
      // `provider_attempts` is not a model-call count: a clip call also pushes the
      // frame through the upload path. The count comes from the trace below; the
      // route's number is kept only as a cross-check.
      observations.clip_route_attempts = clipResponse.provider_attempts;
      const issues = timestampIssues(
        clipResponse.observations.map((entry) => ({
          start_ms: entry.start_ms,
          end_ms: entry.end_ms,
          text: entry.observation,
        })),
        clipResponse.duration_ms,
      );
      const tokenMatch = clipTokenMatch(
        clipResponse.observations.map((entry) => ({ observation: entry.observation })),
        clip.expectedTokens,
      );
      observations.clip = {
        source_id: clipResponse.source_id,
        model: clipResponse.model,
        observed_model: clipResponse.observed_model,
        provider_attempts: clipResponse.provider_attempts,
        measured_duration_ms: clipResponse.duration_ms,
        file_id: clipResponse.file_id,
        observation_count: clipResponse.observations.length,
        timestamp_issues: issues,
        tokens_expected: clip.expectedTokens,
        tokens_found: tokenMatch.found,
        tokens_missing: tokenMatch.missing,
        // Observations are for a human: reported, bounded, never auto-accepted.
        observations: clipResponse.observations.map((entry) => ({
          window: `${String(entry.start_ms)}-${String(entry.end_ms)}ms`,
          confidence: entry.confidence,
          text: boundedExcerpt(entry.observation, 200),
        })),
      };
      // provider_attempts covers the whole operation, upload included; the model
      // call is counted from the trace afterwards, because the dispatches are the
      // evidence, and the two figures are checked against each other rather than
      // one being assumed to mean the other.
      if (clipResponse.observations.length === 0) {
        fail('the provider returned no observations for a clip with visible motion');
      }
      if (issues.length > 0)
        fail(`observation timestamps fall outside the clip: ${issues.join('; ')}`);
      check(
        `live clip observation returned ${String(clipResponse.observations.length)} bounded observations (lexical match ${String(tokenMatch.found.length)}/${String(clip.expectedTokens.length)}: ${tokenMatch.found.join(', ') || 'none'})`,
      );
      // A clip call is one observation dispatch, and may first push the frame
      // through the file upload path; both belong to this operation, and nothing
      // else may appear inside its slice of the trace.
      const clipTrace = accountOperation(
        'clip observation',
        traceBefore,
        [CLIP_UPLOAD_PATH, CLIP_MODEL_PATH],
        2,
      );
      const clipAccount = accountClipCalls(
        clipTrace.dispatches.map((entry) => ({ path: entry.path })),
        clipResponse.provider_attempts,
      );
      calls.clip = clipAccount.modelDispatches;
      observations.clip_call_account = {
        model_dispatches: clipAccount.modelDispatches,
        model_path: CLIP_MODEL_PATH,
        upload_dispatches: clipAccount.uploadDispatches,
        upload_path: CLIP_UPLOAD_PATH,
        provider_attempts_reported: clipResponse.provider_attempts,
      };
      if (clipAccount.issues.length > 0) {
        fail(`clip call accounting: ${clipAccount.issues.join('; ')}`);
      }
      check(
        'clip call accounting: exactly one model dispatch and one upload, and the route attempt count agrees with the observed dispatches',
      );
    }

    // ---- the boundary claim: one attempt per call, no credential in the log --
    // A coarse sweep across every provider path: it catches a retry wherever it
    // happened, but it cannot say which operation caused a dispatch. The
    // per-operation accounting above is what pins each budget to its own call.
    const log = readFileSync(serverLog, 'utf8');
    const trace = parseMediaTrace(log);
    for (const path of [
      '/v1/asr/transcribe',
      '/v1/files',
      '/v1/responses',
      '/v1/images/generations',
      '/v1/segment',
    ]) {
      const tally = tallyAttempts(trace, path);
      observations[`trace_${path.replace(/[^a-z]/gi, '_')}`] = tally;
      if (tally.maxAttempt > 1) {
        fail(`a provider call was retried on ${path} (attempt ${String(tally.maxAttempt)})`);
      }
    }
    observations.trace_paths_seen = [...new Set(trace.map((entry) => entry.path ?? '(none)'))];
    if (log.includes(KEY)) fail('the server log contains the API key');
    if (/\[media-trace\]/.test(log) === false) {
      fail('no media trace lines were recorded, so dispatch counts cannot be accounted for');
    }
    check('every live call accounted for one dispatch, with no retry and no credential in the log');
    writeReport('live results; not fixtures; one call per capability; no retries');
    console.log(`\nBatch D live smoke: PASS (${String(checks.length)} checks)`);
    console.log(`calls: ${JSON.stringify(calls)}`);
    console.log(`evidence: ${EVIDENCE}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    writeReport(`FAILED before completion: ${message}`);
    console.error(`\nFAIL: ${message}`);
    console.error(`evidence: ${EVIDENCE}`);
    process.exitCode = 1;
  } finally {
    server.kill('SIGTERM');
    rmSync(dataRoot, { recursive: true, force: true });
  }
}

function spawnText(command: string, args: string[]): string {
  const out = spawnSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  if (out.status !== 0) {
    fail(
      `${command} failed (exit ${String(out.status)}): ${String(out.stderr ?? '').slice(0, 200)}`,
    );
  }
  return out.stdout;
}

