def _check_header(header, expected, path):
    if tuple(header) != tuple(expected):
        raise AnalysisRefused(
            f'{path}: header {tuple(header)} does not match expected {tuple(expected)}')


def validate_case_rows(rows, expected_families: dict, name: str):
    out = {}
    for row in rows:
        case_id = row['case_id']
        if case_id in out:
            raise AnalysisRefused(f'{name}: duplicate case_id {case_id}')
        if case_id not in expected_families:
            raise AnalysisRefused(f'{name}: unexpected case_id {case_id}')
        family = row['construct_family'].strip()
        if family != expected_families[case_id]:
            raise AnalysisRefused(
                f'{name}: case {case_id} construct_family {family!r} != expected '
                f'{expected_families[case_id]!r}')
        value = _num(row['present_0_1'])
        if value not in (None, 0, 1):
            raise AnalysisRefused(f'{name}: case {case_id} present_0_1={row["present_0_1"]!r}')
        conf = _num(row['confidence_1_5'])
        if conf is not None and conf not in (1, 2, 3, 4, 5):
            raise AnalysisRefused(f'{name}: case {case_id} confidence out of range')
        if value is not None and conf is None:
            raise AnalysisRefused(f'{name}: case {case_id} has a value but no confidence 1-5')
        out[case_id] = {'present': value, 'confidence': conf, 'notes': (row['notes'] or '').strip()}
    missing = set(expected_families) - set(out)
    if missing:
        raise AnalysisRefused(
            f'{name}: incomplete sheet — {len(missing)} case(s) missing, e.g. {sorted(missing)[:3]}')
    return out


def load_case_sheet(path: Path, expected_families: dict, name: str):
    header, rows = read_csv(path)
    _check_header(header, CASE_COLS, path)
    return validate_case_rows(rows, expected_families, name)


def load_variant_sheet(path: Path, expected_ids, name: str):
    header, rows = read_csv(path)
    _check_header(header, VARIANT_COLS, path)
    out = {}
    for row in rows:
        cid = row['variant_case_id']
        if cid in out:
            raise AnalysisRefused(f'{name}: duplicate variant id {cid}')
        if cid not in expected_ids:
            raise AnalysisRefused(f'{name}: unexpected variant id {cid}')
        affordance = _num(row['affordance_count_0_5'])
        if affordance is not None and affordance not in (0, 1, 2, 3, 4, 5):
            raise AnalysisRefused(f'{name}: {cid} affordance_count out of range')
        genuine = _num(row['genuine_hooks_0_1'])
        high = _num(row['opportunity_high_0_1'])
        for field, value in (('genuine_hooks_0_1', genuine), ('opportunity_high_0_1', high)):
            if value not in (None, 0, 1):
                raise AnalysisRefused(f'{name}: {cid} {field} must be 0/1/blank')
        conf = _num(row['confidence_1_5'])
        if any(v is not None for v in (affordance, genuine, high)) and conf is None:
            raise AnalysisRefused(f'{name}: {cid} has values but no confidence 1-5')
        out[cid] = {'affordance': affordance, 'genuine': genuine,
                    'high': high, 'confidence': conf, 'notes': (row['notes'] or '').strip()}
    missing = set(expected_ids) - set(out)
    if missing:
        raise AnalysisRefused(f'{name}: incomplete sheet — {len(missing)} variant(s) missing')
    return out


def load_paraphrase_sheet(path: Path, expected_ids, name: str):
    header, rows = read_csv(path)
    _check_header(header, PARAPHRASE_COLS, path)
    out = {}
    for row in rows:
        cid = row['paraphrase_case_id']
        if cid in out:
            raise AnalysisRefused(f'{name}: duplicate paraphrase id {cid}')
        if cid not in expected_ids:
            raise AnalysisRefused(f'{name}: unexpected paraphrase id {cid}')
        same = _num(row['same_intent_0_1'])
        if same not in (None, 0, 1):
            raise AnalysisRefused(f'{name}: {cid} same_intent must be 0/1/blank')
        conf = _num(row['confidence_1_5'])
        if same is not None and conf is None:
            raise AnalysisRefused(f'{name}: {cid} has a value but no confidence')
        out[cid] = {'same': same, 'confidence': conf, 'notes': (row['notes'] or '').strip()}
    missing = set(expected_ids) - set(out)
    if missing:
        raise AnalysisRefused(f'{name}: incomplete sheet — {len(missing)} paraphrase(s) missing')
    return out


def load_adjudication(path: Path, allowed_ids: set):
    if not path.exists():
        return {}
    header, rows = read_csv(path)
    _check_header(header, ADJ_COLS, path)
    out = {}
    for row in rows:
        item_id = (row['item_id'] or '').strip()
        item_type = (row['item_type'] or '').strip()
        if not item_id:
            continue
        if (item_id, item_type) not in allowed_ids:
            raise AnalysisRefused(
                f'adjudication: unknown item ({item_id!r}, {item_type!r}); expected one of '
                f'case/variant:<field>/paraphrase item ids')
        value = _num(row['adjudicator_value'])
        if value is None:
            continue
        if value not in (0, 1):
            raise AnalysisRefused(f'adjudication: {item_id} value must be 0/1')
        if (item_id, item_type) in out:
            raise AnalysisRefused(f'adjudication: duplicate item ({item_id!r}, {item_type!r})')
        out[(item_id, item_type)] = value
    return out


