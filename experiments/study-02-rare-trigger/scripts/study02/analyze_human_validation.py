def expected_item_ids(data):
    allowed = set()
    for case_id in set(data['panel']) | set(data['real']):
        allowed.add((case_id, 'case'))
    for case_id in data['variants']:
        for field in ('genuine', 'high'):
            allowed.add((f'{case_id}:{field}', 'variant'))
    for case_id in data['paraphrases']:
        allowed.add((f'{case_id}:same_intent', 'paraphrase'))
    return allowed


def load_sheets(pkg: Path, data):
    sheet_paths = {
        'case_a': pkg / 'sheets' / 'coder-A.csv',
        'case_b': pkg / 'sheets' / 'coder-B.csv',
        'variant_a': pkg / 'sheets' / 'variant-labels.csv',
        'variant_b': pkg / 'sheets' / 'variant-labels-coder-B.csv',
        'paraphrase_a': pkg / 'sheets' / 'paraphrase-intent.csv',
        'paraphrase_b': pkg / 'sheets' / 'paraphrase-intent-coder-B.csv',
        'adjudication': pkg / 'sheets' / 'adjudication.csv',
    }
    expected_families = {}
    for case_id, case in data['panel'].items():
        expected_families[case_id] = case['construct_family']
    for case_id, entry in data['real'].items():
        expected_families[case_id] = 'game:any' if entry['rule_set'] == 'game' else 'focus:any'
    sheets = {
        'case_a': load_case_sheet(sheet_paths['case_a'], expected_families, 'coder-A'),
        'case_b': load_case_sheet(sheet_paths['case_b'], expected_families, 'coder-B'),
        'variant_a': load_variant_sheet(sheet_paths['variant_a'], data['variants'], 'variant-labels'),
        'variant_b': load_variant_sheet(sheet_paths['variant_b'], data['variants'],
                                        'variant-labels-coder-B'),
        'paraphrase_a': load_paraphrase_sheet(sheet_paths['paraphrase_a'], data['paraphrases'],
                                              'paraphrase-intent'),
        'paraphrase_b': load_paraphrase_sheet(sheet_paths['paraphrase_b'], data['paraphrases'],
                                              'paraphrase-intent-coder-B'),
        'adjudication': load_adjudication(sheet_paths['adjudication'], expected_item_ids(data)),
        'hashes': {key: sha256_file(path) for key, path in sheet_paths.items()
                   if path.exists() and key != 'adjudication'},
    }
    coded_cases = sum(1 for row in sheets['case_a'].values() if row['present'] is not None)
    coded_cases += sum(1 for row in sheets['case_b'].values() if row['present'] is not None)
    coded_variants = sum(1 for row in sheets['variant_a'].values()
                         if row['high'] is not None or row['genuine'] is not None)
    coded_paraphrases = sum(1 for row in sheets['paraphrase_a'].values() if row['same'] is not None)
    if coded_cases + coded_variants + coded_paraphrases == 0:
        raise AnalysisRefused(
            'the package is unfilled: no coded values exist in any sheet. This package is '
            'MATERIALS ONLY — appoint coders, collect completed sheets, then run the analysis. '
            'Use --self-test for the SYNTHETIC-TEST-ONLY mechanics check. No human coding has '
            'occurred and no result may be reported from an unfilled package.')
    return sheets


