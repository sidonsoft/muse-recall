def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--package', default=str(PKG), help='human-validation package directory')
    parser.add_argument('--out', help='write the result JSON to this path')
    parser.add_argument('--emit-disputes', help='write the adjudication request CSV to this path')
    parser.add_argument('--self-test', action='store_true',
                        help='run the SYNTHETIC-TEST-ONLY mechanics self-test (no files written)')
    args = parser.parse_args(argv)
    pkg = Path(args.package)
    if args.self_test:
        return self_test(pkg)
    try:
        data = load_package(pkg)
        sheets = load_sheets(pkg, data)
    except AnalysisRefused as exc:
        print(f'REFUSED: {exc}', file=sys.stderr)
        return 3
    result, disputes = compute_metrics(data, sheets, synthetic=False)
    transcript = render_transcript(result)
    print(transcript)
    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(
            json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False) + '\n',
            encoding='utf-8')
        print(f'\nwrote result JSON to {out_path}')
    if args.emit_disputes:
        dispute_path = Path(args.emit_disputes)
        dispute_path.parent.mkdir(parents=True, exist_ok=True)
        import io as _io
        buf = _io.StringIO()
        writer = csv.DictWriter(buf, fieldnames=ADJ_COLS, lineterminator='\n')
        writer.writeheader()
        for dispute in disputes:
            writer.writerow(dispute)
        dispute_path.write_text(buf.getvalue(), encoding='utf-8')
        print(f'wrote {len(disputes)} adjudication request row(s) to {dispute_path}')
    if result['verdict']['overall'] == 'FAIL':
        print(f"\nGATE: FAIL — see review/04 §7.4 / §8 for the required pre-freeze actions")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
