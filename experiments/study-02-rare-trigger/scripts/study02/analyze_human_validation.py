def bootstrap_over_clusters_variants(variant_ids, stat_fn, label):
    generator = rng(label)
    stats = []
    for _ in range(BOOT_REPS):
        sample = [variant_ids[generator.randrange(len(variant_ids))] for _ in variant_ids]
        value = stat_fn(sample)
        if value is not None:
            stats.append(value)
    return bootstrap_ci(stats, label)


def aggregate(statuses):
    if any(status == 'FAIL' for status in statuses):
        return 'FAIL'
    if all(status == 'PASS' for status in statuses):
        return 'PASS'
    if all(status == 'NOT-ESTIMABLE' for status in statuses):
        return 'NOT-ESTIMABLE'
    return 'CONDITIONAL'


