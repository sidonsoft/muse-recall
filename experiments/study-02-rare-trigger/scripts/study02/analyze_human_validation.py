#!/usr/bin/env python3
"""Analyse completed Study 02 human-validation sheets and compute the pre-declared gate.

WHAT THIS IS
------------
Stdlib-only analysis for the package under ``human-validation/`` (generated by
``build_human_validation_package.py``). It implements the metrics and the
PASS / CONDITIONAL / FAIL gate pre-declared in
``review/04-HUMAN-VALIDATION-PROTOCOL.md`` §7 (A1–A11).

It:
  * refuses to run on a missing, incomplete, duplicated or malformed coder sheet;
  * reads the two coder sheets, the two per-coder variant sheets, the two per-coder
    paraphrase sheets and the (optional) adjudication sheet;
  * recomputes the frozen trigger-zone instrument reading for every case from the
    package files (so the instrument comparison is not stored anywhere);
  * reports Cohen's κ per construct family and overall, raw agreement, panel
    sensitivity/specificity against planted truth, arm-differential instrument
    error, unresolved rate, label κ, hook agreement and paraphrase conflicts,
    with cluster-bootstrap (30 pilot scenarios) or Wilson intervals as pre-declared;
  * emits the overall and per-target verdicts.

``--self-test`` builds **SYNTHETIC-TEST-ONLY** dummy codes in memory (never written
to ``sheets/``) and checks the gate arithmetic and the incomplete-sheet refusal.
AI-generated dummy codes are never human data and are never stored.

DETERMINISM
-----------
No clock, no network, no model calls. Bootstrap streams are seeded from SHA-256 of
a fixed label. JSON output is sorted. The same inputs always produce the same bytes.

USAGE
-----
    python3 scripts/study02/analyze_human_validation.py --self-test
    python3 scripts/study02/analyze_human_validation.py
    python3 scripts/study02/analyze_human_validation.py --out analysis/hv-result.json \
        --emit-disputes sheets/adjudication-requests.csv
"""
