def render_transcript(result):
    lines = []
    lines.append('=' * 88)
    lines.append('Study 02 — human-validation gate analysis')
    lines.append('=' * 88)
    if result['synthetic']:
        lines.append(f'*** {SYNTHETIC_LABEL}: dummy codes, mechanics test only — NOT human data ***')
    lines.append(f"evidence status: {result['evidence_status']}")
    lines.append('')
    counts = result['counts']
    lines.append('COUNTS')
    for key in ('census_runs', 'panel_cases', 'core_positives', 'blind_spot_probes',
                'negatives', 'false_positive_probes', 'variants', 'paraphrase_texts'):
        lines.append(f'  {key:28s} {counts[key]}')
    lines.append('')
    lines.append('METRICS (pre-declared thresholds: review/04 §7.2)')
    for key, metric in result['metrics'].items():
        if not isinstance(metric, dict) or 'status' not in metric:
            continue
        value = metric.get('value')
        shown = 'n/a' if value is None else f'{value:.3f}'
        ci = metric.get('ci95') or metric.get('wilson95')
        ci_text = '' if ci is None else f'  95%CI [{ci[0]:.3f}, {ci[1]:.3f}]'
        lines.append(f'  {key:46s} {shown:>7s}{ci_text}  -> {metric["status"]}')
    lines.append('')
    lines.append('PER CONSTRUCT FAMILY (panel; inter-coder and instrument-vs-human)')
    for family, row in result['per_construct_family_panel'].items():
        ik = 'n/a' if row['inter_coder_kappa'] is None else f"{row['inter_coder_kappa']:.3f}"
        ivk = 'n/a' if row['instrument_vs_human_kappa'] is None else f"{row['instrument_vs_human_kappa']:.3f}"
        lines.append(f'  {family:20s} n={row["cases"]:2d}  κ(A,B)={ik}  κ(instrument,human)={ivk}')
    lines.append('')
    lines.append('VERDICT')
    lines.append(f"  overall: {result['verdict']['overall']}")
    for target, value in result['verdict']['by_target'].items():
        lines.append(f'  {target:32s} {value}')
    lines.append(f"  allowed use: {result['verdict']['allowed_use']}")
    lines.append('')
    lines.append('UNRESOLVED / DISPUTES')
    lines.append(f"  unresolved case items: {len(result['unresolved_items'])}")
    lines.append(f"  disputes: case={len(result['disputes']['case'])} "
                 f"variant={len(result['disputes']['variant'])} "
                 f"paraphrase={len(result['disputes']['paraphrase'])}")
    lines.append('')
    lines.append('NOTES')
    for note in result['notes']:
        lines.append(f'  - {note}')
    lines.append('=' * 88)
    return '\n'.join(lines)


