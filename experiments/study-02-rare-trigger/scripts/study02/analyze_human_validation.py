def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def load_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def read_csv(path: Path):
    if not path.exists():
        raise AnalysisRefused(f'missing sheet: {path}')
    with path.open('r', encoding='utf-8', newline='') as handle:
        reader = csv.DictReader(handle)
        header = tuple(reader.fieldnames or ())
        rows = [dict(row) for row in reader]
    return header, rows


def rng(label: str) -> random.Random:
    seed = int(hashlib.sha256(f'{SEED}|{label}'.encode('utf-8')).hexdigest()[:16], 16)
    return random.Random(seed)


def _num(text):
    text = (text or '').strip()
    if text == '':
        return None
    return int(text)


def cohen_kappa(pairs):
    """Cohen's κ for two raters over binary labels; None when undefined."""
    pairs = [(int(a), int(b)) for a, b in pairs]
    n = len(pairs)
    if n == 0:
        return None
    agree = sum(1 for a, b in pairs if a == b)
    po = agree / n
    pa1 = sum(1 for a, _ in pairs if a == 1) / n
    pb1 = sum(1 for _, b in pairs if b == 1) / n
    pe = pa1 * pb1 + (1 - pa1) * (1 - pb1)
    if pe >= 1.0:
        return None
    return (po - pe) / (1 - pe)


def raw_agreement(pairs):
    pairs = list(pairs)
    if not pairs:
        return None
    return sum(1 for a, b in pairs if a == b) / len(pairs)


def wilson_interval(k: int, n: int, z: float = Z):
    if n == 0:
        return None
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return [max(0.0, centre - half), min(1.0, centre + half)]


def percentile(values, q: float):
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    pos = (len(ordered) - 1) * q
    low = int(math.floor(pos))
    high = min(low + 1, len(ordered) - 1)
    frac = pos - low
    return ordered[low] + (ordered[high] - ordered[low]) * frac


def bootstrap_ci(values, label: str, reps: int = BOOT_REPS):
    """Percentile 95% CI from a list of replicate statistics (None values skipped)."""
    valid = [v for v in values if v is not None]
    if len(valid) < 100:
        return None
    return [percentile(valid, 0.025), percentile(valid, 0.975)]


