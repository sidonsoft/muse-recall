def split_panel_case(text: str):
    m1 = text.index(PANEL_MARK_BASE) + len(PANEL_MARK_BASE)
    m2 = text.index('<!--HV-BASELINE-END-->')
    m3 = text.index(PANEL_MARK_OUT) + len(PANEL_MARK_OUT)
    m4 = text.index('<!--HV-OUTPUT-END-->')
    return text[m1:m2].strip(), text[m3:m4].strip()


def load_instrument():
    if str(SCORING) not in sys.path:
        sys.path.insert(0, str(SCORING))
    import frozen  # noqa: F401  (verifies frozen copies)
    import trigger_zones
    return trigger_zones


def load_package(pkg: Path = PKG):
    truth_path = pkg / 'panel-truth.json'
    map_path = pkg / 'reference' / 'case-map.json'
    manifest_path = pkg / 'sampling-manifest.json'
    for path in (truth_path, map_path, manifest_path):
        if not path.exists():
            raise AnalysisRefused(f'missing package file: {path}')
    truth = load_json(truth_path)
    case_map = load_json(map_path)
    manifest = load_json(manifest_path)
    panel = {c['case_id']: c for c in truth['cases']}
    real = {e['case_id']: e for e in case_map['real']}
    variants = {e['variant_case_id']: e for e in case_map['variants']}
    paraphrases = {e['paraphrase_case_id']: e for e in case_map['paraphrases']}
    # cluster id per case: census rows nest in their pilot scenario; panel rows are independent
    clusters = {}
    for case_id, entry in real.items():
        clusters[case_id] = entry['scenario_id']
    for case_id in panel:
        clusters[case_id] = case_id
    return {
        'pkg': pkg,
        'truth': truth,
        'panel': panel,
        'real': real,
        'variants': variants,
        'paraphrases': paraphrases,
        'clusters': clusters,
        'manifest': manifest,
        'hashes': {
            'panel-truth.json': sha256_file(truth_path),
            'reference/case-map.json': sha256_file(map_path),
            'sampling-manifest.json': sha256_file(manifest_path),
        },
    }


