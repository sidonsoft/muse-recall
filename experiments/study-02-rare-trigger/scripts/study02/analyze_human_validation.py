def instrument_readings(data):
    trigger_zones = load_instrument()
    readings = {}
    for case_id, entry in data['real'].items():
        out_html = (STUDY / entry['output_file']).read_text(encoding='utf-8')
        base_html = (STUDY / 'corpus' / 'variants' / f"{entry['variant_id']}.html").read_text(
            encoding='utf-8')
        result = trigger_zones.classify(out_html, entry['stratum'], base_html)
        readings[case_id] = 1 if result['exposed'] else 0
    for case_id, case in data['panel'].items():
        text = (data['pkg'] / 'cases' / 'panel' / f'{case_id}.html').read_text(encoding='utf-8')
        base_frag, out_frag = split_panel_case(text)
        stratum = PANEL_STRATUM[case['rule_set']]
        result = trigger_zones.classify(out_frag, stratum, base_frag)
        readings[case_id] = 1 if result['trigger_types'][case['construct_family']]['exposed'] else 0
    return readings


def consensus_rows(items, a_rows, b_rows, adjudication, item_type):
    """Resolve two coder rows + adjudication into (value, state) per item id."""
    resolved = {}
    disputes = []
    for item_id in sorted(items):
        a = a_rows.get(item_id, {}).get('present') if item_type == 'case' else None
        b = b_rows.get(item_id, {}).get('present') if item_type == 'case' else None
        if item_type != 'case':
            a = a_rows.get(item_id)
            b = b_rows.get(item_id)
        av = a
        bv = b
        if av is not None and bv is not None and av == bv:
            resolved[item_id] = {'value': av, 'state': 'agree'}
            continue
        adjudicated = adjudication.get((item_id, item_type))
        if adjudicated in (0, 1):
            resolved[item_id] = {'value': adjudicated, 'state': 'adjudicated'}
            continue
        resolved[item_id] = {'value': None, 'state': 'unresolved'}
        disputes.append({
            'item_id': item_id,
            'item_type': item_type,
            'coder_a_value': '' if av is None else av,
            'coder_b_value': '' if bv is None else bv,
            'adjudicator_value': '',
            'adjudicator_confidence_1_5': '',
            'final_rationale': '',
            'adjudicator_initials': '',
            'adjudicated_utc': '',
        })
    return resolved, disputes


